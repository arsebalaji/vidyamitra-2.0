export type UILang = (typeof languageRegistry)[number]["code"];
export function languageInfo(code: string) {
  return languageRegistry.find((l) => l.code === code) ?? languageRegistry[0];
}
export function isSelectableLanguage(code: string): code is UILang {
  return languageRegistry.some((l) => l.code === code && l.selectable);
}
export function resolveLanguage(code: string) {
  return languageInfo(isSelectableLanguage(code) ? code : "te");
}
